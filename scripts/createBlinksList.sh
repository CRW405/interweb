#!/usr/bin/env bash

set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
blinks_dir="$script_dir/../medias/blinks"
output="$script_dir/blinks.js"

{
	printf '%s\n' '// This file is generated by scripts/createBlinksList.sh.'
	printf '%s\n' 'const blinks = ['

	while IFS= read -r -d '' file; do
		# Escape the filename for use as a JavaScript string literal.
		escaped_file="$(printf '%s' "$file" | sed 's/[\\"]/\\&/g')"
		printf '\t"%s",\n' "$escaped_file"
	done < <(find "$blinks_dir" -maxdepth 1 -type f -printf '%f\0' | LC_ALL=C sort -z)

	printf '%s\n' '];' 'export default blinks;'
} >"$output"

printf 'Created %s\n' "$output"
